local U=require('util');local A=require('article')
local clean=assert(A.sanitize('<div class="entry-content"><h2>标题</h2><p>第一段 &amp; 第二段 &#x5357;&#20140;</p><p>尾段<br/>换行</p><script>alert(1)</script><nav>导航</nav><p class="related">推荐</p><img src="https://example.com/x" onerror="bad()" alt="示意图"/><a href="javascript:bad()">文字</a></div>'))
assert(clean:find('<h2>标题</h2>',1,true),clean)
assert(clean:find('<p>第一段 &amp; 第二段 南京</p>',1,true),clean)
assert(clean:find('<p>尾段<br/>换行</p>',1,true),clean)
assert(clean:find('[图片：示意图]',1,true),clean)
for _,s in ipairs({'alert','导航','推荐','onerror','javascript','href=','src='}) do assert(not clean:find(s,1,true),s..' leaked') end
local plain=A.sanitize('<p>&lt;代码&gt; &unknown; &quot;测试&quot;</p>')
assert(plain=='<p>&lt;代码&gt; &amp;unknown; &quot;测试&quot;</p>',plain)
assert(A.sanitize('<p> </p><p><br/></p><p>&nbsp;</p><p>正文</p>')=='<p>正文</p>','Empty CMS paragraphs must not add blank pages')
assert(not A.public_body('<html><nav>'..string.rep('导航',300)..'</nav></html>'))
assert(not A.public_body('<article>'..string.rep('文章',150)..'登录后阅读全文</article>'))
assert(not A.public_body('<script id="__NEXT_DATA__">{"props":"invalid"}</script>'))
local full=A.public_body('<nav>导航</nav><article><p>'..string.rep('正文内容。',100)..'</p></article>')
assert(full and full:find('<p>',1,true))
local news=A.public_body('<nav>新闻导航</nav><div class="left_zw"><p>'..string.rep('新闻正文。',100)..'</p></div><aside>相关新闻</aside>')
assert(news and news:find('新闻正文。',1,true) and not news:find('新闻导航',1,true) and not news:find('相关新闻',1,true))
local feed=U.feed('<rss><channel><item><title>标题</title><link>https://example.com/one</link><description>&lt;p&gt;一段&lt;/p&gt;</description></item><item><title>全文</title><content:encoded><![CDATA[<p>全文一段内容</p><p>二段内容</p>]]></content:encoded></item></channel></rss>','测试')
assert(#feed==2 and feed[1].html=='<p>一段</p>' and feed[1].content_kind=='summary')
assert(feed[2].html=='<p>全文一段内容</p><p>二段内容</p>' and feed[2].content_kind=='feed')
assert(not A.feed_book(feed[1]),'A summary must still fetch its article on demand')
local direct=A.feed_book(feed[2]);assert(direct and direct:sub(1,4)=='PK\3\4','Full feed must produce a readable book directly')
feed[2].truncated=true;assert(not A.feed_book(feed[2]),'Truncated feeds must fetch the complete article')
local item={title='测试 & 阅读',source='测试订阅',link='https://example.com/article'}
assert(#A.id(item)==24 and A.id(item)==A.id({link=item.link,title='changed'}))
local book=A.epub(item,clean,'summary')
assert(book:sub(1,4)=='PK\3\4' and book:find('当前仅有订阅摘要',1,true))
assert(U.write('/var/tmp/mydash-article-test.epub',book))
print('ARTICLE_SELFTEST_OK sanitizer, entities, paragraphs, full/summary distinction, stable id, EPUB')
